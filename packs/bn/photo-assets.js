/* =========================================================
   packs/bn/photo-assets.js — 人物框可選的「圖素」清單
   =========================================================
   來源：img/圖素版/ 的去背 PNG（1200×700，RGBA）。
   ⚠ 插畫的**墨迹**只佔畫布寬 40~62%（四周是透明邊），所以圖素不是擺進公版的
   「雙人人物框」（那個框的長寬比 1.70＝圖素的**畫布**比例），而是擺進設計端另外標的
   **圖素定位框**（packs/bn/stock-placements.js，長寬比 1.10＝雙人圖素**墨迹**的比例），
   並且貼合的是墨迹不是畫布——墨迹邊界由 bn-editor 開機用 canvas 量 alpha，
   所以**換圖素、加圖素都不用回來改任何數字**（見 slotInk()）。

   使用者 2026-09-16 指示：圖素「預設直接套用進去人物框」，並做成縮圖可以挑。
   所以 defaultId 那一張在沒有存檔（或存檔還沒經過這一版）時會自動放進人物框，
   右欄的縮圖列可以隨時換一張，也仍然可以自己上傳照片蓋掉。

   ⚠ 這份表就是目錄：瀏覽器讀不到資料夾清單（跟 themes.js 的 images 同一個
   限制），所以新增圖素＝把 png 丟進 img/圖素版/ 再在這裡加一行。
   換圖不用改這裡也不用跑任何腳本：覆蓋 img/ 裡的檔、重新整理即可。

   ⚠ 路徑一律「相對專案根目錄」，頁面自己補相對層級
   （tools/bn-editor.html 的 ASSET_BASE）。不要在這裡內嵌 base64——
   見 CLAUDE.md「不要做的事」那一條。
   ⚠ 部署到 Linux 主機（GitLab）時檔名大小寫必須完全一致。

   name 只是縮圖下面的標籤，取檔名去掉副檔名（沒有額外語意）：
   01-1／01-2 與 03-1／03-2 看起來是同一個場景的配色變體，
   02 是純道具（沒有人），挑哪一張由使用者看縮圖決定。
   ========================================================= */
